"""Package the offline demo with original rock layers and a precise hero sprite."""
from pathlib import Path
from datetime import datetime, timedelta, timezone
import base64
import hashlib
import io
import json
import subprocess
import sys
from PIL import Image

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent
OUTPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "ecology-walk.html"
ART = PROJECT / "美术素材/地图/20261030-modular-cave-playground"
SCRIPTS = ["contours.js", "authored-profiles.js", "module-rules.js", "terrain-shapes.js", "world-data.js",
           "engine.js", "renderer.js", "assembly-inspector.js", "app.js"]
PORT_VERSION = "ecology-module-rules-v2"
SHAPE_VERSION = "ecology-author-shapes-v2"
subprocess.run([sys.executable, str(HERE / "trace-authored.py")], check=True, stdout=subprocess.PIPE)
sources = {
    "hero": PROJECT / "美术素材/地图/20261029-wfc-cave-kit/sources/hero-scale-reference.png",
    "back": ART / "sources/backwall-clean.png",
    "rockMaterial": PROJECT / "美术素材/地图/20261031-cave-ecology-studies-v1/sources/rock-material-v2.png",
    "bridgeDesign": PROJECT / "美术素材/地图/20261031-cave-ecology-studies-v1/sources/bridge-authored-v2.png",
}
sources.update({f"panel{i}": ART / f"exports-v3/foreground/module-{i+1}.png" for i in range(6)})
media = {}
identities = []
for name, path in sources.items():
    image = Image.open(path).convert("RGBA")
    original_size = image.size
    if name == "back":
        image.thumbnail((640, 640))
    if name == "hero":
        image.thumbnail((120, 132))
    if name in ("rockMaterial", "bridgeDesign"):
        image.thumbnail((768, 512))
    data = io.BytesIO()
    if name == "bridgeDesign":
        image.save(data, "WEBP", lossless=True, exact=True, method=6)
    else:
        image.save(data, "WEBP", quality=86, method=6)
    media[name] = "data:image/webp;base64," + base64.b64encode(data.getvalue()).decode("ascii")
    identities.append({"name": name, "path": str(path), "nativeSize": original_size,
                       "packagedSize": image.size, "sourceSha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                       "packagedSha256": hashlib.sha256(data.getvalue()).hexdigest(),
                       "packagedBytes": len(data.getvalue()),
                       "encoding": {"format": "WEBP", "lossless": name == "bridgeDesign",
                                    "alphaPreserved": True,
                                    **({"exactTransparentRgb": True} if name == "bridgeDesign" else {"quality": 86})},
                       "role": {"rockMaterial": "canonical-rock-material", "bridgeDesign": "authored-bridge-design"}
                       .get(name, "original-separated-layer"),
                       **({"moduleSize": [623, 414], "artCoreSize": [495, 495 * original_size[1] / original_size[0]],
                           "artCoreOffset": [64, 0], "interfaceOutsideSourceArt": True,
                           "aspectPolicy": "preserve-native-ratio",
                           "nativeSourceBytesUnmodified": True} if name == "bridgeDesign" else {})})
sheet_path = PROJECT / "美术素材/地图/20261031-cave-ecology-studies-v1/sources/vegetation-sheet.png"
sheet = Image.open(sheet_path).convert("RGBA")
regions = {"grass": (0, 0, 512, 512), "orange": (512, 0, 1024, 512),
           "teal": (1024, 0, 1536, 512), "ivory": (0, 512, 590, 1024),
           "vine": (600, 512, 970, 1024), "fern": (970, 512, 1536, 1024)}
plant_media = {}
plant_regions = []
for name, rect in regions.items():
    cut = sheet.crop(rect)
    bounds = cut.getchannel("A").point(lambda a: 255 if a > 12 else 0).getbbox()
    assert bounds, f"Missing cutout {name}"
    cut = cut.crop(bounds)
    native_size = cut.size
    cut.thumbnail((160, 200))
    data = io.BytesIO()
    cut.save(data, "WEBP", quality=90, method=6)
    plant_media[name] = "data:image/webp;base64," + base64.b64encode(data.getvalue()).decode("ascii")
    plant_regions.append({"name": name, "sourceRegion": rect, "alphaBoundsInRegion": bounds,
                          "nativeCutoutSize": native_size, "packagedSize": cut.size,
                          "bytes": len(data.getvalue())})
assets = {"hero": media["hero"], "back": media["back"], "rockMaterial": media["rockMaterial"],
          "bridgeDesign": media["bridgeDesign"],
          "panels": [media[f"panel{i}"] for i in range(6)],
          "plants": plant_media}
contour_path = ART / "art-silhouettes.json"
contours = json.loads(contour_path.read_text(encoding="utf-8"))
(HERE / "contours.js").write_text(
    "// Generated by build.py from the original art-silhouettes.json; do not edit.\n"
    + "globalThis.ECOLOGY_CONTOURS=" + json.dumps(contours["panels"], separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
source_files = [{"path": str(HERE / name), "sha256": hashlib.sha256((HERE / name).read_bytes()).hexdigest()}
                for name in ["view.html", *SCRIPTS, "build.py",
                             "authored-profile-input.json", "trace-authored.py"]]
identity_input = {
    "schema": "ecology-build-v2", "portVersion": PORT_VERSION, "shapeVersion": SHAPE_VERSION,
    "sources": [{"file": Path(entry["path"]).name, "sha256": entry["sha256"]}
                for entry in source_files],
    "assets": [{"name": entry["name"], "sourceSha256": entry["sourceSha256"],
                "packagedSha256": entry["packagedSha256"]} for entry in identities],
    "contourSourceSha256": hashlib.sha256(contour_path.read_bytes()).hexdigest(),
    "vegetationSourceSha256": hashlib.sha256(sheet_path.read_bytes()).hexdigest(),
    "vegetationRegions": plant_regions,
}
build_id = hashlib.sha256(json.dumps(identity_input, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":")).encode("utf-8")).hexdigest()
parts = [(HERE / "view.html").read_text(encoding="utf-8"),
         "<script>\nwindow.ECOLOGY_BUILD_ID=" + json.dumps(build_id)
         + ";\nwindow.ECOLOGY_ASSETS=" + json.dumps(assets, separators=(",", ":")) + ";\n</script>"]
for name in SCRIPTS:
    parts.append("<script>\n" + (HERE / name).read_text(encoding="utf-8") + "\n</script>")
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
assert OUTPUT.stat().st_size < 1_000_000, "Inline demo exceeds 1 MB."
manifest = {
    "date": "2026-10-31", "purpose": "Modular ecological cave authoring walk demo; no Unity integration.",
    "sources": identities, "output": str(OUTPUT.resolve()), "bytes": OUTPUT.stat().st_size,
    "outputSha256": hashlib.sha256(OUTPUT.read_bytes()).hexdigest(),
    "buildId": build_id, "buildIdentityInput": identity_input,
    "portVersion": PORT_VERSION, "shapeVersion": SHAPE_VERSION,
    "sourceFiles": source_files,
    "contourSource": {"path": str(contour_path), "sha256": hashlib.sha256(contour_path.read_bytes()).hexdigest()},
    "vegetation": {"source": str(sheet_path), "sourceSha256": hashlib.sha256(sheet_path.read_bytes()).hexdigest(),
                   "nativeSize": sheet.size, "regions": plant_regions,
                   "note": "Ivory and fern extend beyond ideal grid cells; explicit non-overlapping crops preserve whole sprites. Alpha preserved."},
    "staticEcologyConceptsConsumed": False,
    "dynamicLayers": ["stream-current", "waterfall", "splash", "grass", "mushroom", "vine", "root",
                      "ore-dust", "bridge-construction", "crumbling-rock", "cargo-transfer"],
    "spineProjectCreated": False,
}
records = HERE / "build-records"
records.mkdir(exist_ok=True)
stamp = datetime.now(timezone(timedelta(hours=8))).strftime("%Y%m%d-%H%M%S-%f")
record_path = records / f"{stamp}-{build_id[:12]}.json"
manifest["buildRecord"] = str(record_path)
with record_path.open("x", encoding="utf-8") as record:
    record.write(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
(HERE / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(json.dumps({"output": str(OUTPUT), "bytes": manifest["bytes"], "buildId": build_id,
                  "sourceLayers": len(identities), "buildRecord": str(record_path)}, ensure_ascii=False))
