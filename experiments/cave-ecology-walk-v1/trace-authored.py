"""Derive the bridge ceiling and retain the explicit soil-top foot guide."""
from pathlib import Path
import hashlib
import json
from PIL import Image

HERE = Path(__file__).resolve().parent
INPUT = HERE / "authored-profile-input.json"
config = json.loads(INPUT.read_text(encoding="utf-8"))
source = (HERE / config["source"]).resolve()
image = Image.open(source).convert("RGBA")
assert image.size == (config["nativeWidth"], config["nativeHeight"])
scale = config["displayWidth"] / image.width
inset = config["insetX"]
width = config["moduleWidth"]
alpha = image.getchannel("A")
roof = []
floor = []
left_floor = config["nativeFloorGuide"][0][1] * scale
right_floor = config["nativeFloorGuide"][-1][1] * scale
for x in range(width + 1):
    native_x = min(image.width - 1, max(0, round((x - inset) / scale)))
    top = 0
    while top < image.height and alpha.getpixel((native_x, top)) >= config["alphaThreshold"]:
        top += 1
    bottom = image.height - 1
    while bottom >= 0 and alpha.getpixel((native_x, bottom)) >= config["alphaThreshold"]:
        bottom -= 1
    assert 0 < top < bottom < image.height - 1, (x, top, bottom)
    port_roof = (left_floor if x < width / 2 else right_floor) - 128
    distance = min(x - inset, inset + config["displayWidth"] - x)
    t = max(0, min(1, distance / 8))
    ease = t * t * (3 - 2 * t)
    roof.append(round(port_roof + ((top - 1) * scale - port_roof) * ease, 6))
    floor.append(round((bottom + 1) * scale, 6))
guide = [[round(inset + x * scale, 6), round(y * scale, 6)]
         for x, y in config["nativeFloorGuide"]]
guide = [[0, round(left_floor, 6)], *guide, [width, round(right_floor, 6)]]
record = {
    "version": config["version"],
    "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "inputSha256": hashlib.sha256(INPUT.read_bytes()).hexdigest(),
    "nativeSize": list(image.size),
    "moduleWidth": width,
    "displayWidth": config["displayWidth"],
    "displayHeight": image.height * scale,
    "insetX": inset,
    "scale": scale,
    "floor": guide,
    "roof": [[x, y] for x, y in enumerate(roof)],
    "native": {"roof": roof, "floor": floor},
    "bridgeAnchors": [round(inset + x * scale, 6) for x in config["nativeBridgeAnchors"]],
    "crumblePlate": [[round(inset + x * scale, 6), round(y * scale, 6)]
                     for x, y in config["nativeCrumblePlate"]],
    "collisionSource": "Explicit soil foot guide and alpha-traced ceiling; rubble is visual occlusion.",
}
(HERE / "authored-profiles.js").write_text(
    "// Generated by trace-authored.py; source pixels are unchanged.\n"
    + "globalThis.ECOLOGY_AUTHORED_PROFILES={bridge:"
    + json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "};\n",
    encoding="utf-8",
)
print(json.dumps({"profile": record["version"], "sourceSha256": record["sourceSha256"],
                  "displaySize": [record["displayWidth"], record["displayHeight"]],
                  "floorGuidePoints": len(guide), "ceilingColumns": len(roof)}))
