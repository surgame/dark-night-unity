async function add(id, source, expected, role, anchor) {
  const bytes = await readFile(source), hash = createHash("sha256").update(bytes).digest("hex");
  if (expected && hash !== expected.sha256) throw new Error("Source changed since reference sampling: " + source);
  let width = expected?.nativeWidth, height = expected?.nativeHeight;
  if (source.endsWith(".png")) { width = bytes.readUInt32BE(16); height = bytes.readUInt32BE(20); }
  const mime = source.endsWith(".webp") ? "image/webp" : "image/png";
  records[id] = { w: width, h: height, uri: "data:" + mime + ";base64," + bytes.toString("base64"),
    anchor: anchor || null, role };
  provenance.push({ id, source: path.resolve(source), width, height, sha256: hash, role, anchor: anchor || null,
    sourceBytesUnchanged: true });
}
