import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import vm from "node:vm";
import { runtimeFiles } from "./source-files.mjs";

const root = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(root, "../..");
const output = path.resolve(process.argv[2]);
const target = path.join(root, "assets/feature-backdrops");
await mkdir(output, { recursive: true });
const context = vm.createContext({ window: {}, console });
for (const file of runtimeFiles) vm.runInContext(await readFile(path.join(root, "src", file), "utf8"), context);
const D = context.window.DN, inputs = [], used = new Set();
for (const scene of D.catalog.filter(s => s.feature)) {
  if (used.has(scene.layout)) continue;
  used.add(scene.layout);
  const w = new D.World(scene);
  inputs.push({ id: scene.layout, solids: w.solids.filter(s => !s.dynamic).map(s => [s.x, s.y, s.w, s.h]) });
}
const inputFile = path.join(output, "inputs.json");
await writeFile(inputFile, JSON.stringify(inputs, null, 2) + "\n");
const assembly = path.join(project, "Game/Library/ScriptAssemblies/DarkNights.Core.dll");
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const before = hash(await readFile(assembly));
execFileSync("dotnet", ["run", "--project", path.join(root, "style-sampler/StyleSampler.csproj"),
  "--", inputFile, output], { stdio: "inherit" });
execFileSync("python", [path.join(root, "style-sampler/encode.py"), output, target], { stdio: "inherit" });
if (before !== hash(await readFile(assembly))) throw new Error("Source assembly changed during native sampling.");
const records = {}, sources = [];
for (const input of inputs) {
  const file = path.join(target, input.id + ".png"), bytes = await readFile(file);
  records["backdrop-" + input.id] = { w: 768, h: 336,
    uri: "data:image/png;base64," + bytes.toString("base64"), role: "独立H5新特性洞穴原生背景" };
  sources.push({ id: input.id, source: file, sha256: hash(bytes), width: 768, height: 336 });
}
await writeFile(path.join(root, "src/feature-assets.js"),
  "(function (D) {\n  \"use strict\";\n  // Generated by build-feature-assets.mjs; native backgrounds only.\n" +
  "  Object.assign(D.assetRecords, " + JSON.stringify(records) + ");\n" +
  "  D.featureAssets = " + JSON.stringify(inputs.map(x => x.id)) + ";\n})(window.DN);\n");
await writeFile(path.join(target, "source.json"), JSON.stringify({
  method: "BackgroundContourBaker + BackgroundPageBaker; static occupancy; native 2px scale",
  assembly, assemblySha256: before, inputFile, inputSha256: hash(await readFile(inputFile)),
  unityStarted: false, originalSourceModified: false, assets: sources
}, null, 2) + "\n");
console.log(JSON.stringify({ layouts: inputs.length, assemblySha256: before, target }));
