// 单调三次插值保留作者点的起伏，避免切线过冲形成新台阶或自交。
function tangent(points, index) {
  if (index === 0 || index === points.length - 1) return 0;
  const left = (points[index][1] - points[index-1][1]) / (points[index][0] - points[index-1][0]);
  const right = (points[index+1][1] - points[index][1]) / (points[index+1][0] - points[index][0]);
  return left * right <= 0 ? 0 : 2 * left * right / (left + right);
}

function curve(points) {
  const n = value => Number(value.toFixed(5));
  let path = `M${points[0][0]} ${points[0][1]}`;
  for (let i = 0; i < points.length - 1; i++) {
    const a = points[i], b = points[i+1], dx = (b[0]-a[0])/3;
    path += ` C${n(a[0]+dx)} ${n(a[1]+dx*tangent(points,i))} ${n(b[0]-dx)} ${n(b[1]-dx*tangent(points,i+1))} ${b[0]} ${b[1]}`;
  }
  return path;
}

function sample(points, x) {
  let index = points.findIndex((point, i) => i < points.length-1 && x >= point[0] && x <= points[i+1][0]);
  if (index < 0) return x < points[0][0] ? points[0][1] : points[points.length-1][1];
  const a = points[index], b = points[index+1], dx = b[0]-a[0], t = (x-a[0])/dx;
  const h00 = 2*t*t*t-3*t*t+1, h10 = t*t*t-2*t*t+t;
  const h01 = -2*t*t*t+3*t*t, h11 = t*t*t-t*t;
  return h00*a[1]+h10*dx*tangent(points,index)+h01*b[1]+h11*dx*tangent(points,index+1);
}

